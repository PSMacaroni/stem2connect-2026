"""Turn docs/video.md into a teleprompter sheet: one sentence per line, with beats and a running clock.

Usage: uv run python scripts/teleprompter.py            (writes docs/video-teleprompter.md)
       uv run python scripts/teleprompter.py --check    (exit 1 if the sheet is stale, for CI)

Nothing here is typed by hand: every word count and every time comes from the narration in `docs/video.md`, so
the sheet cannot drift from the script. Re-run it after any edit to the script.

The pace, WPM, is an assumption, not a measurement; the sheet says so and tells the reader to time shot 1 against
it before recording the rest. Pause lengths are a speaking guide, not a budget: the shot list in `docs/video.md`
is what has to fit inside 6:00.
"""

import pathlib
import re
import sys
import textwrap

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC, OUT = ROOT / "docs" / "video.md", ROOT / "docs" / "video-teleprompter.md"
WPM = 145  # the same unhurried pace docs/video.md budgets against
WRAP = 96

HEAD = re.compile(r"^### (\d+)\. (.+?) \(ends (\d+):(\d+)\)\s*—\s*(.+)$")


def shots(text: str) -> list[dict]:
    """Every `### n. ...` heading with the narration (`> ` lines) that follows it."""
    out: list[dict] = []
    for line in text.splitlines():
        if m := HEAD.match(line):
            out.append({"n": m[1], "title": m[2], "ends": int(m[3]) * 60 + int(m[4]),
                        "screen": m[5], "say": []})
        elif line.startswith("> ") and out:
            out[-1]["say"].append(line[2:].strip())
    return out


def sentences(words: str) -> list[str]:
    """Split on sentence ends, keeping the punctuation. Abbreviations do not appear in this narration."""
    return [s.strip() for s in re.split(r"(?<=[.?!])\s+", words) if s.strip()]


def clock(sec: float) -> str:
    """Rounded, not truncated, so this sheet and the budget line in docs/video.md agree on the same seconds."""
    s = round(sec)
    return f"{s // 60}:{s % 60:02d}"


def spoken(say: list[str]) -> str:
    """The narration actually read aloud: the sentence marked (cut first) is cut by default, so it is not counted."""
    return " ".join(s for s in sentences(" ".join(say)) if "**(cut first)**" not in s)


def sheet(text: str) -> str:
    sh = shots(text)
    total = sum(len(spoken(s["say"]).split()) for s in sh)
    lines = [
        "# Teleprompter sheet",
        "",
        "Generated from `docs/video.md` by `scripts/teleprompter.py`. Do not edit this file: edit the script and",
        "re-run the generator, or the two will disagree.",
        "",
        "**How to read it.** One sentence per line, because a line is a breath. `//` is a beat: stop, let the",
        "sentence land, then go on. `///` is a real pause, a second or two, usually while the app is working and",
        "the viewer is reading the screen. Never run two lines together to save time; if you are short of time,",
        "cut a sentence instead.",
        "",
        f"**Pace.** The clock below assumes {WPM} words a minute, which is unhurried. That is an assumption, not a",
        "measurement of you. Read shot 1 aloud once against a stopwatch: if it lands near its mark you can trust",
        "the rest of the sheet; if it runs long you speak slower than this, so cut sentences, do not speed up.",
        "",
        f"**Total.** {total} words of narration, about {clock(total / WPM * 60)} of speech at {WPM} a minute,",
        f"inside a hard limit of 6:00. That leaves about {360 - total / WPM * 60:.0f} seconds for every pause in",
        "the video put together: the beats, the thinking, and the time the app spends working. It is enough for an",
        "unhurried read and not enough to waste. Every shot below ends with a `///`; the three worth holding",
        "longest are after the abstain in shot 4, after the orange warning in shot 7, and before the last line.",
        "",
        "---",
        "",
    ]
    run = 0.0
    for s in sh:
        said = " ".join(s["say"])
        n_words = len(spoken(s["say"]).split())
        secs = n_words / WPM * 60
        budget = s["ends"] - run
        head = (f"## Shot {s['n']} — {s['title']}  ·  say it by {clock(s['ends'])}  ·  "
                f"{n_words} words ≈ {secs:.0f}s of speech in a {budget:.0f}s slot")
        screen = re.sub(r"^on screen:\s*", "", s["screen"], flags=re.IGNORECASE)
        lines += [head, "", f"**On screen:** {screen}", ""]
        if budget - secs < 1:
            lines += [("> No cushion here against the shot-list clock: the words alone fill the slot, so any pause "
                       "puts you behind it. That is recoverable (the 6:00 limit is what matters, and the total "
                       "below still fits), but have the click ready before you start talking."), ""]
        for sent in sentences(said):
            mark = "  //"
            if "**(cut first)**" in sent:
                sent = "~~" + sent.replace("**(cut first)**", "").strip() + "~~"
                mark = "   ← CUT by default (see the budget note in docs/video.md)"
            for i, chunk in enumerate(textwrap.wrap(sent, WRAP) or [""]):
                lines.append(("    " if i else "  ") + chunk)
            lines[-1] += mark
            lines.append("")
        lines += ["  ///  breathe, then set up the next shot", "", "---", ""]
        run += secs
    lines += ["", f"End of narration at about {clock(run)} of speech, before any pause is counted.", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    made = sheet(SRC.read_text(encoding="utf-8"))
    if "--check" in argv:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if have != made:
            print(f"FAIL  {OUT.relative_to(ROOT)} is stale; re-run scripts/teleprompter.py")
            return 1
        print(f"ok    {OUT.relative_to(ROOT)} matches docs/video.md")
        return 0
    OUT.write_text(made, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
